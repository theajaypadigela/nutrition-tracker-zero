#!/usr/bin/env node
/**
 * Bundles the Worker's migrations (worker/migrations/*.sql) into src/embedded/migrations.generated.ts so the app can create its
 * own database on first launch. Run after adding a migration: `npm run gen:migrations`. A test fails when the file is stale.
 */
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', '..', 'worker', 'migrations');
const out = path.join(__dirname, '..', 'src', 'embedded', 'migrations.generated.ts');

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))} },`).join('\n');
const text = `// GENERATED by scripts/gen-migrations.js from worker/migrations. Do not edit; run \`npm run gen:migrations\`.
import type { Migration } from './d1';

export const MIGRATIONS: Migration[] = [
${body}
];
`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('migrations.generated.ts is out of date: run `npm run gen:migrations`');
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${files.length} migrations)`);
}
